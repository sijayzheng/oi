CREATE INDEX if not exists idx_bstate_user ON sys_message_broadcast_state (user_id, deleted);
COMMENT ON TABLE sys_message_broadcast_state IS '站内信广播个性化状态（惰性创建）';
COMMENT ON COLUMN sys_message_broadcast_state.message_id IS '消息 id（sys_message.id）';
COMMENT ON COLUMN sys_message_broadcast_state.user_id IS '用户 id';
COMMENT ON COLUMN sys_message_broadcast_state.read_status IS '已读状态；0=未读 1=已读';
COMMENT ON COLUMN sys_message_broadcast_state.archived IS '归档标记；1=已归档';

-- ========== 任务调度：任务定义 ==========
-- 业务含义：任务调度定义表，一条记录即一个可调度任务，承载触发/重试/超时/并发/告警全量配置。
-- 使用场景：@OiScheduled 自动建档 + 运维在线增删改（全部免重启即时生效）。
-- 注意事项：job_key 与 deleted 组合唯一；trigger_value 统一字符串存储（CRON 或毫秒周期）；
--           enabled=FALSE 表示暂停（配置保留，不参与触发）。
CREATE TABLE if not exists sys_job
(
    id                      BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    -- 主键
    job_key                 VARCHAR(100)                          NOT NULL, -- 任务业务键；点分命名（如 report.daily）；与 deleted 组合唯一；@OiScheduled 按 jobKey 关联，创建后禁止修改
    name                    VARCHAR(100)                          NOT NULL, -- 任务名称；管理界面展示用
    trigger_type            VARCHAR(20)                           NOT NULL, -- 触发类型 JobTriggerType：CRON=CRON 表达式 / FIXED_RATE=固定频率 / FIXED_DELAY=固定延迟
    trigger_value           VARCHAR(100)                          NOT NULL, -- 触发值；CRON 存 6 位表达式（如 0 * * * * *）；FIXED_RATE/FIXED_DELAY 存毫秒周期（>=1000）
    timeout_millis          BIGINT      DEFAULT 0                 NOT NULL, -- 超时时间（毫秒）；>0 启用超时保护（强制中断并标记 TIMEOUT）；0=不限时
    retry_policy            VARCHAR(30) DEFAULT 'FIXED_INTERVAL'  NOT NULL,
    -- 重试策略 JobRetryPolicy：FIXED_INTERVAL=固定间隔 / EXPONENTIAL_BACKOFF=指数退避（含抖动）
    max_retry_count         INT         DEFAULT 0                 NOT NULL, -- 最大重试次数；0=不重试
    retry_initial_interval  BIGINT      DEFAULT 60000             NOT NULL, -- 初始重试间隔（毫秒）；固定间隔策略等待时长、指数退避基数
    retry_max_interval      BIGINT      DEFAULT 600000            NOT NULL, -- 最大重试间隔（毫秒）；指数退避封顶值；须 >= 初始间隔
    retry_include           VARCHAR(1000),                                  -- 可重试异常白名单；类型全限定名模式（逗号分隔，* 尾通配）；命中即重试
    retry_exclude           VARCHAR(1000),                                  -- 不可重试异常黑名单；命中即直接判失败（优先级高于白名单）
    conflict_strategy       VARCHAR(20) DEFAULT 'DISCARD'         NOT NULL, -- 并发冲突策略 JobConflictStrategy：DISCARD=丢弃（默认）/ QUEUE=排队等待
    alert_failure_threshold INT         DEFAULT 0                 NOT NULL, -- 连续失败告警阈值；>0 时连续失败达阈值触发站内信告警；0=不启用
    remark                  VARCHAR(500),                                   -- 备注
    enabled                 BOOLEAN     DEFAULT TRUE              NOT NULL, -- 启用状态：TRUE=启用中参与调度 / FALSE=已暂停
    create_by               BIGINT,                                         -- 创建人用户 id；0=系统（@OiScheduled 自动建档）
    create_time             TIMESTAMP   DEFAULT CURRENT_TIMESTAMP NOT NULL,
    -- 审计字段
    update_by               BIGINT,                                         -- 最后修改人
    update_time             TIMESTAMP   DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
    -- 自动刷新
    deleted                 BIGINT      DEFAULT 0                 NOT NULL, -- 软删标记；唯一键 uk_job_key 包含本列
    CONSTRAINT uk_job_key UNIQUE (job_key, deleted)
);
COMMENT ON TABLE sys_job IS '任务调度定义';
COMMENT ON COLUMN sys_job.job_key IS '任务业务键；点分命名；与 deleted 组合唯一；@OiScheduled 按 jobKey 关联';
COMMENT ON COLUMN sys_job.trigger_type IS '触发类型；CRON / FIXED_RATE / FIXED_DELAY';
COMMENT ON COLUMN sys_job.trigger_value IS '触发值；CRON 表达式或毫秒周期';
COMMENT ON COLUMN sys_job.timeout_millis IS '超时毫秒；0=不限时';
COMMENT ON COLUMN sys_job.retry_policy IS '重试策略；FIXED_INTERVAL / EXPONENTIAL_BACKOFF';
COMMENT ON COLUMN sys_job.retry_include IS '可重试异常白名单；类型模式，逗号分隔';
COMMENT ON COLUMN sys_job.retry_exclude IS '不可重试异常黑名单；优先级高于白名单';
COMMENT ON COLUMN sys_job.conflict_strategy IS '并发冲突策略；DISCARD / QUEUE';
COMMENT ON COLUMN sys_job.alert_failure_threshold IS '连续失败告警阈值；0=不启用';

-- ========== 任务调度：执行记录 ==========
-- 业务含义：一次调度触发一行（重试在同一行累计），完整记录执行状态/异常/耗时。
-- 使用场景：执行详情页、连续失败统计、死信溯源。
-- 注意事项：append + 有限更新（RUNNING -> 终态）；增长快，建议按 start_time 定期归档；
--           job_id 为逻辑外键（任务删除后历史保留）。
CREATE TABLE if not exists sys_job_log
(
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    -- 主键
    job_id          BIGINT                                NOT NULL, -- 任务 id（sys_job.id）；逻辑外键，任务删除后历史保留
    job_key         VARCHAR(100)                          NOT NULL, -- 任务业务键快照；任务删除后历史仍可读
    job_name        VARCHAR(100)                          NOT NULL, -- 任务名称快照；不随任务改名变化
    trigger_source  VARCHAR(20) DEFAULT 'SCHEDULE'        NOT NULL, -- 触发来源：SCHEDULE=调度 / MANUAL=手动 / REPLAY=死信重放
    execute_status  VARCHAR(20)                           NOT NULL, -- 执行状态 JobExecuteStatus：PENDING/RUNNING/SUCCESS/FAILED/TIMEOUT/DEAD/SKIPPED
    attempt_no      INT         DEFAULT 0                 NOT NULL, -- 当前执行轮次；0=首次，n=第 n 次重试
    retry_count     INT         DEFAULT 0                 NOT NULL, -- 累计重试次数（终态时）
    error_type      VARCHAR(255),                                   -- 异常类型名
    error_stack     VARCHAR(4000),                                  -- 异常信息（message+堆栈）；超长截断
    start_time      TIMESTAMP                             NOT NULL, -- 执行开始时间
    end_time        TIMESTAMP,                                      -- 结束时间；RUNNING 为空
    duration_millis BIGINT,                                         -- 耗时（毫秒）；= end-start
    executor        VARCHAR(100),                                   -- 执行机标识（主机:端口）；集群排查用
    create_time     TIMESTAMP   DEFAULT CURRENT_TIMESTAMP NOT NULL
    -- 记录创建时间
);
CREATE INDEX if not exists idx_job_log_job ON sys_job_log (job_key, start_time);
CREATE INDEX if not exists idx_job_log_status ON sys_job_log (execute_status, start_time);
COMMENT ON TABLE sys_job_log IS '任务执行记录';
COMMENT ON COLUMN sys_job_log.job_key IS '任务业务键快照';
COMMENT ON COLUMN sys_job_log.trigger_source IS '触发来源；SCHEDULE/MANUAL/REPLAY';
COMMENT ON COLUMN sys_job_log.execute_status IS '执行状态；PENDING/RUNNING/SUCCESS/FAILED/TIMEOUT/DEAD/SKIPPED';
COMMENT ON COLUMN sys_job_log.error_stack IS '异常信息（message+堆栈）；超长截断';

-- ========== 任务调度：重试明细 ==========
-- 业务含义：一次尝试一行（含首试），与执行记录一对多；完整追溯每次重试的
--           触发时间、异常堆栈、单次耗时与下次重试时刻。
-- 使用场景：执行详情页重试过程展示。
-- 注意事项：append-only。
CREATE TABLE if not exists sys_job_retry_detail
(
    id                      BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    -- 主键
    log_id                  BIGINT                              NOT NULL, -- 执行记录 id（sys_job_log.id）
    attempt_no              INT                                 NOT NULL, -- 尝试轮次；0=首次，n=第 n 次重试
    attempt_status          VARCHAR(20)                         NOT NULL, -- 本轮状态：RUNNING/SUCCESS/FAILED/TIMEOUT
    error_type              VARCHAR(255),                                 -- 本轮异常类型
    error_stack             VARCHAR(4000),                                -- 本轮异常信息；超长截断
    attempt_start_time      TIMESTAMP                           NOT NULL, -- 本轮开始时间
    attempt_end_time        TIMESTAMP,                                    -- 本轮结束时间
    attempt_duration_millis BIGINT,                                       -- 本轮耗时（毫秒）
    next_retry_at           TIMESTAMP,                                    -- 本轮失败后的下次重试时刻（退避+抖动后）；耗尽/成功为空
    create_time             TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL
);
CREATE INDEX if not exists idx_job_retry_log ON sys_job_retry_detail (log_id, attempt_no);
COMMENT ON TABLE sys_job_retry_detail IS '任务重试明细（append-only）';
COMMENT ON COLUMN sys_job_retry_detail.log_id IS '执行记录 id';
COMMENT ON COLUMN sys_job_retry_detail.attempt_no IS '尝试轮次；0=首次';
COMMENT ON COLUMN sys_job_retry_detail.next_retry_at IS '下次重试时刻；含退避+抖动';

-- ========== 任务调度：死信 ==========
-- 业务含义：重试耗尽仍失败的任务转入死信，完整保留任务上下文快照与执行历史关联，
--           支持人工排查与手动重放（重放重置重试计数重新走完整流程）。
-- 使用场景：死信管理页；重放成功/失败状态流转。
-- 注意事项：处理完毕允许物理删除清理；job_config 为 JSON 快照，任务后续变化不影响死信。
CREATE TABLE if not exists sys_job_dead_letter
(
    id                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    -- 主键
    job_id            BIGINT                                NOT NULL, -- 任务 id（sys_job.id）；任务可能已删除，仅作定位参考
    job_key           VARCHAR(100)                          NOT NULL, -- 任务业务键快照
    job_name          VARCHAR(100)                          NOT NULL, -- 任务名称快照
    source_log_id     BIGINT                                NOT NULL, -- 死信来源执行记录 id；经其关联 sys_job_retry_detail 追溯全量历史
    job_config        VARCHAR(4000),                                  -- 任务配置快照（JSON）；死信产生时刻的触发/重试/超时配置
    error_type        VARCHAR(255),                                   -- 最终异常类型
    error_stack       VARCHAR(4000),                                  -- 最终异常信息；超长截断
    total_retry_count INT         DEFAULT 0                 NOT NULL, -- 累计重试次数
    status            VARCHAR(20) DEFAULT 'PENDING'         NOT NULL, -- 处理状态：PENDING=待处理 / RESOLVED=已重放成功 / REPLAY_FAILED=重放失败
    replay_time       TIMESTAMP,                                      -- 最近重放时间
    create_time       TIMESTAMP   DEFAULT CURRENT_TIMESTAMP NOT NULL,
    -- 死信产生时间
    update_time       TIMESTAMP   DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP
);
CREATE INDEX if not exists idx_dead_letter_key ON sys_job_dead_letter (job_key, status);
COMMENT ON TABLE sys_job_dead_letter IS '任务死信（重试耗尽）';
COMMENT ON COLUMN sys_job_dead_letter.source_log_id IS '死信来源执行记录 id';
COMMENT ON COLUMN sys_job_dead_letter.job_config IS '任务配置快照（JSON）';
COMMENT ON COLUMN sys_job_dead_letter.status IS '处理状态；PENDING/RESOLVED/REPLAY_FAILED';
