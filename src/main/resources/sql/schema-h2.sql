    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    -- 主键
    message_id  BIGINT            NOT NULL, -- 消息 id（sys_message.id）
    user_id     BIGINT            NOT NULL, -- 用户 id
    read_status TINYINT DEFAULT 0 NOT NULL, -- 已读状态；0=未读 1=已读
    read_time   TIMESTAMP,                  -- 首次已读时间
    archived    TINYINT DEFAULT 0 NOT NULL, -- 归档标记；1=已归档
    deleted     BIGINT  DEFAULT 0 NOT NULL, -- 软删标记；用户删除该广播时置为主键 id
