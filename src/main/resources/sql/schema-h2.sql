-- =============================================================================
-- Oi 系统初始化表结构（H2）
-- 通用约定：
--   1. 审计字段四件套：create_by / create_time / update_by / update_time，由应用层统一写入；
--   2. 软删除：deleted 默认 0（未删除），删除时写入本行主键 id；
--      所有业务查询必须显式携带 deleted = 0 条件；含唯一约束的表均以 (业务键, deleted) 组合唯一，
--      保证软删后原业务键可被重新创建；
--   3. 关联表（无审计字段）采用物理删除；
--   4. enabled 字段为布尔语义：TRUE=正常（原 NORMAL）/ FALSE=禁用（原 DISABLED）；
--   5. 本文件由 spring.sql.init.mode=always 在每次启动时执行，DDL 需保证幂等或仅用于空库初始化。
-- =============================================================================

-- ========== 用户 ==========
-- 业务含义：系统账号表，所有登录主体的唯一凭证来源。
-- 使用场景：登录认证（sa-token）、个人信息维护、后台用户管理。
CREATE TABLE if not exists sys_user
(
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    -- 主键；IDENTITY 自增，禁止手工指定；被 sys_user_role.user_id、sys_log.user_id、create_by/update_by 引用
    username    VARCHAR(50)                           NOT NULL, -- 登录名；与 deleted 组合唯一（软删后可重建同名）；登录凭证，创建后不建议修改（展示层引用 id，不受影响）
    password    VARCHAR(100)                          NOT NULL, -- 登录密码密文；BCrypt 哈希（约 60 字符），VARCHAR(100) 留余量；严禁存明文，校验使用 BCrypt.matches
    nickname    VARCHAR(50) DEFAULT ''                NOT NULL,
    -- 用户昵称/显示名；默认空串；前端展示优先级：nickname > username
    mobile      VARCHAR(20),
    -- 手机号；最长 20 字符（含国际区号 +86 等写法）；可用于登录、找回密码、短信通知；已有 idx_user_mobile 索引
    email       VARCHAR(100),
    -- 邮箱；用于通知与找回密码；格式校验由应用层完成（H2 无 CHECK 约束）
    avatar      VARCHAR(255),
    -- 头像文件 id（字符串形态）；统一文件管理服务 sys_file 的唯一引用，展示时换取临时访问地址
    enabled     BOOLEAN     DEFAULT TRUE              NOT NULL, -- 启用状态：TRUE=正常（可登录）/ FALSE=禁用（拒绝登录）；默认 TRUE
    remark      VARCHAR(255),
    -- 备注；管理员维护的补充说明，不参与业务逻辑
    create_by   BIGINT,
    -- 创建人用户 id；0 或 NULL=系统初始化；审计字段，应用层写入
    create_time TIMESTAMP   DEFAULT CURRENT_TIMESTAMP NOT NULL,
    -- 创建时间；默认当前时间；审计字段
    update_by   BIGINT,
    -- 最后修改人用户 id；审计字段
    update_time TIMESTAMP   DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
    -- 更新时间；行被 UPDATE 时自动刷新；乐观校验可参考此字段
    deleted     BIGINT      DEFAULT 0                 NOT NULL, -- 软删标记；0=未删除，删除时=本行主键 id；唯一键 uk_user_username 包含本列
    CONSTRAINT uk_user_username UNIQUE (username, deleted)
);
CREATE INDEX if not exists idx_user_mobile ON sys_user (mobile);
-- 手机号索引；支撑按手机号登录/查询场景

-- ========== 角色 ==========
-- 业务含义：角色表，RBAC 权限模型的中间层，用户-角色-菜单三级关联的枢纽。
-- 使用场景：权限分配、后台角色管理；代码中常以 code 做权限判断。
CREATE TABLE if not exists sys_role
(
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    -- 主键；被 sys_user_role.role_id、sys_role_menu.role_id 引用
    code        VARCHAR(50)                         NOT NULL, -- 角色编码；与 deleted 组合唯一；代码中用于权限逻辑（如 admin/user）；创建后不建议修改
    name        VARCHAR(50)                         NOT NULL,
    -- 角色显示名；前端下拉/列表展示用
    sort        INT       DEFAULT 0                 NOT NULL,
    -- 排序号；同状态内数值越小越靠前；默认 0
    enabled     BOOLEAN   DEFAULT TRUE              NOT NULL, -- 启用状态：TRUE=正常 / FALSE=禁用；禁用后该角色的权限不再生效
    remark      VARCHAR(255),
    -- 备注
    create_by   BIGINT,
    -- 创建人用户 id；审计字段
    create_time TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    -- 创建时间；审计字段
    update_by   BIGINT,
    -- 最后修改人；审计字段
    update_time TIMESTAMP DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
    -- 更新时间；自动刷新
    deleted     BIGINT    DEFAULT 0                 NOT NULL, -- 软删标记；唯一键 uk_role_code 包含本列
    CONSTRAINT uk_role_code UNIQUE (code, deleted)
);

-- ========== 用户-角色 ==========
-- 业务含义：用户与角色的多对多关联表。
-- 注意事项：无审计与软删字段，解绑即物理删除；绑定时须校验 user_id/role_id 均存在且未禁用。
CREATE TABLE if not exists sys_user_role
(
    user_id BIGINT NOT NULL,
    -- 用户 id；逻辑外键 → sys_user.id（H2 不建物理外键，应用层保证一致性）
    role_id BIGINT NOT NULL,
    -- 角色 id；逻辑外键 → sys_role.id
    PRIMARY KEY (user_id, role_id)
);
CREATE INDEX if not exists idx_user_role_role ON sys_user_role (role_id);
-- 反向索引；支撑"查某角色下的全部用户"

-- ========== 菜单 / 权限 ==========
-- 业务含义：菜单与权限点表，树形结构（目录 → 菜单 → 按钮），是前端动态路由与后端鉴权的统一数据源。
-- 使用场景：左侧导航渲染、页面按钮级权限（perms）、角色授权树。
CREATE TABLE if not exists sys_menu
(
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    -- 主键；被 sys_role_menu.menu_id、sys_menu.parent_id 引用
    parent_id   BIGINT    DEFAULT 0                 NOT NULL, -- 父菜单 id；0=根节点；树形结构，层级：目录(DIRECTORY) → 菜单(MENU) → 按钮(BUTTON)；已有 idx_menu_parent 索引
    name        VARCHAR(50)                         NOT NULL,
    -- 菜单/按钮名称；导航与授权树展示用
    type        VARCHAR(20)                         NOT NULL, -- 节点类型 MenuType：DIRECTORY=目录（仅分组，无路由）/ MENU=菜单（可跳转页面）/ BUTTON=按钮（页面内操作权限点）
    path        VARCHAR(200),
    -- 前端路由路径；DIRECTORY/MENU 使用（如 /system/user），BUTTON 留空
    component   VARCHAR(200),
    -- 前端组件路径；MENU 使用（指向视图组件），DIRECTORY/BUTTON 留空
    perms       VARCHAR(100),
    -- 权限标识；BUTTON 使用，格式"模块:动作"（如 user:add）；后端接口鉴权依据；已有 idx_menu_perms 索引
    icon        VARCHAR(50),
    -- 图标标识；导航栏渲染
    sort        INT       DEFAULT 0                 NOT NULL,
    -- 同级排序号；越小越靠前
    visible     BOOLEAN   DEFAULT TRUE              NOT NULL, -- 显示状态：TRUE=显示（导航正常渲染）/ FALSE=隐藏（整棵子树不下发前端：不渲染、不生成路由、不参与权限计算）
    enabled     BOOLEAN   DEFAULT TRUE              NOT NULL, -- 启用状态：TRUE=正常 / FALSE=禁用；FALSE 时整棵子树权限不生效
    create_time TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    -- 创建时间；审计字段
    update_time TIMESTAMP DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
    -- 更新时间；自动刷新
    deleted     BIGINT    DEFAULT 0                 NOT NULL  -- 软删标记
);
CREATE INDEX if not exists idx_menu_parent ON sys_menu (parent_id);
CREATE INDEX if not exists idx_menu_perms ON sys_menu (perms);

-- ========== 角色-菜单 ==========
-- 业务含义：角色与菜单/权限点的授权关联表。
-- 注意事项：无审计与软删字段，取消授权即物理删除；授权前须校验 menu.type 与角色用途匹配。
CREATE TABLE if not exists sys_role_menu
(
    role_id BIGINT NOT NULL,
    -- 角色 id；逻辑外键 → sys_role.id
    menu_id BIGINT NOT NULL,
    -- 菜单/权限点 id；逻辑外键 → sys_menu.id
    PRIMARY KEY (role_id, menu_id)
);
CREATE INDEX if not exists idx_role_menu_menu ON sys_role_menu (menu_id);
-- 反向索引；支撑"查某菜单被哪些角色持有"（删除菜单前的影响检查）

-- ========== 操作日志 ==========
-- 业务含义：用户操作行为日志表，仅插入不修改（append-only）。
-- 使用场景：操作审计、异常排查、行为统计。
-- 注意事项：增长最快的表，建议按 create_time 定期归档清理；username 为快照冗余，不随用户资料变化。
CREATE TABLE if not exists sys_log
(
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    -- 主键
    user_id     BIGINT,
    -- 操作人用户 id；匿名/未登录请求为 NULL；逻辑外键 → sys_user.id
    username    VARCHAR(50),
    -- 操作人登录名快照；冗余存储，防止用户改名/软删后日志无法溯源
    module      VARCHAR(50),
    -- 业务模块标识；如 auth / online，与 Controller 分组对应
    action      VARCHAR(50),
    -- 操作动作；如 login / kick / export
    level       VARCHAR(10) DEFAULT 'INFO'            NOT NULL, -- 日志级别 LogLevel：DEBUG=调试 / INFO=信息 / WARN=警告 / ERROR=错误
    request_id  VARCHAR(64),                                    -- 请求 ID；写入时生成的短追踪标识，用于跨记录关联与详情溯源
    uri         VARCHAR(200),
    -- 请求路径；超长截断
    method      VARCHAR(10),
    -- HTTP 方法；GET/POST/PUT/DELETE 等
    ip          VARCHAR(64),
    -- 客户端 IP；兼容 IPv6 最长 64
    params      VARCHAR(4000),                                  -- 请求参数 JSON；入库前截断至 4000 字符，防止大报文撑爆
    result      VARCHAR(20) DEFAULT 'SUCCESS'         NOT NULL, -- 执行结果 LogResult：SUCCESS=成功 / FAIL=失败
    error_msg   VARCHAR(500),
    -- 失败原因摘要；截断至 500 字符；成功时为 NULL
    duration    INT,
    -- 执行耗时（毫秒）；用于慢操作分析
    create_time TIMESTAMP   DEFAULT CURRENT_TIMESTAMP NOT NULL
    -- 记录时间；默认当前时间；已有 idx_log_time 支撑时间范围检索
);
CREATE INDEX if not exists idx_log_time ON sys_log (create_time);
CREATE INDEX if not exists idx_log_user ON sys_log (user_id, create_time);
-- 组合索引；支撑"查某用户某时间段内的操作"

-- ========== 参数配置 ==========
-- 业务含义：系统级参数配置表（键值对），运行时可变配置的统一存储。
-- 使用场景：站点名称等系统参数；应用启动/运行时按 key 读取。
CREATE TABLE if not exists sys_config
(
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    -- 主键
    config_key   VARCHAR(100)  NOT NULL,                    -- 参数键；与 deleted 组合唯一；点分命名风格（如 site.name）；代码中以常量引用，创建后禁止修改
    config_value VARCHAR(2000) NOT NULL DEFAULT '',         -- 参数值；统一按字符串存储，按 value_type 解析；最长 2000
    value_type   VARCHAR(20)   NOT NULL DEFAULT 'STRING',   -- 值类型 ConfigValueType：STRING=字符串 / NUMBER=数字 / BOOLEAN=布尔 / JSON=结构化对象；决定前端编辑控件与解析方式
    name         VARCHAR(100)  NOT NULL,                    -- 参数名称；管理界面展示用（如"站点名称"）
    remark       VARCHAR(255),
    -- 备注；说明该参数的作用与取值建议
    create_by    BIGINT,
    -- 创建人；审计字段
    create_time  TIMESTAMP              DEFAULT CURRENT_TIMESTAMP NOT NULL,
    -- 创建时间；审计字段
    update_by    BIGINT,
    -- 最后修改人；审计字段
    update_time  TIMESTAMP              DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
    -- 更新时间；自动刷新
    deleted      BIGINT                 DEFAULT 0 NOT NULL, -- 软删标记；唯一键 uk_config_key 包含本列
    CONSTRAINT uk_config_key UNIQUE (config_key, deleted)
);

-- ========== 字典类型 ==========
-- 业务含义：数据字典的类型定义表，枚举值下拉数据的分组入口。
-- 使用场景：性别、状态类等枚举下拉框的数据源管理。
CREATE TABLE if not exists sys_dict_type
(
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    -- 主键
    dict_type   VARCHAR(50)                         NOT NULL, -- 字典编码；与 deleted 组合唯一；命名小写下划线（如 user_status）；被 sys_dict_item.dict_type 冗余引用，修改前须同步字典项
    name        VARCHAR(100)                        NOT NULL,
    -- 字典名称；如"用户状态"
    enabled     BOOLEAN   DEFAULT TRUE              NOT NULL, -- 启用状态：TRUE=正常 / FALSE=禁用；禁用后其字典项不对外提供
    remark      VARCHAR(255),
    -- 备注
    create_by   BIGINT,
    -- 创建人；审计字段
    create_time TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    -- 创建时间；审计字段
    update_by   BIGINT,
    -- 最后修改人；审计字段
    update_time TIMESTAMP DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
    -- 更新时间；自动刷新
    deleted     BIGINT    DEFAULT 0                 NOT NULL, -- 软删标记；唯一键 uk_dict_type_code 包含本列
    CONSTRAINT uk_dict_type_code UNIQUE (dict_type, deleted)
);

-- ========== 字典项 ==========
-- 业务含义：数据字典的具体取值项，每个字典类型下的选项列表。
-- 使用场景：下拉框选项渲染、值-标签翻译（item_code → item_label）。
CREATE TABLE if not exists sys_dict_item
(
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    -- 主键
    dict_type  VARCHAR(50)          NOT NULL, -- 所属字典编码；冗余 sys_dict_type.dict_type（查询免 join）；两者须保持同步
    item_code  VARCHAR(50)          NOT NULL, -- 项编码；业务实际存储值；与 dict_type、deleted 组合唯一
    item_label VARCHAR(100)         NOT NULL,
    -- 项显示名；前端展示的文案（如 NORMAL→"正常"）
    sort       INT     DEFAULT 0    NOT NULL,
    -- 项排序号；同字典内越小越靠前
    enabled    BOOLEAN DEFAULT TRUE NOT NULL, -- 项启用状态：TRUE=正常 / FALSE=禁用；禁用后不再出现在下拉选项，但历史数据仍可回显
    remark     VARCHAR(255),
    -- 备注
    deleted    BIGINT  DEFAULT 0    NOT NULL, -- 软删标记；唯一键 uk_dict_item 包含本列
    CONSTRAINT uk_dict_item UNIQUE (dict_type, item_code, deleted)
);
CREATE INDEX if not exists idx_dict_item_type ON sys_dict_item (dict_type, deleted);
-- 组合索引；支撑"按字典编码取全部有效项"的高频查询

-- ========== 代码生成：表配置 ==========
-- 业务含义：代码生成器的表级配置，一张待生成业务表对应一行。
-- 使用场景：导入业务表结构后维护类名/模块/功能名与主子表关联配置，驱动 FreeMarker 模板渲染。
CREATE TABLE if not exists gen_table
(
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    -- 主键
    table_name      VARCHAR(100)                          NOT NULL, -- 业务表名；如 sys_notice；同一表仅允许导入一次
    table_comment   VARCHAR(200),                                   -- 业务表注释；如"通知公告"
    class_name      VARCHAR(100)                          NOT NULL, -- 实体类名主干（不含 Sys 前缀与模型后缀）；如 Notice → SysNotice / SysNoticeVO
    module_name     VARCHAR(50)                           NOT NULL, -- 业务模块名；对应包名与前端路由段（如 sys）
    business_name   VARCHAR(50)                           NOT NULL, -- 业务名；对应接口路径段与前端文件名（如 notice → /notice）
    function_name   VARCHAR(100)                          NOT NULL, -- 功能名；界面展示用（如"通知公告"）
    author          VARCHAR(50) DEFAULT 'sijay'           NOT NULL, -- 生成代码的 @author 署名
    parent_table_id BIGINT,                                         -- 主子表场景：主表 gen_table.id；单表场景为 NULL
    fk_column       VARCHAR(100),                                   -- 主子表场景：子表外键列名（关联 parent_table_id 主表主键）
    create_time     TIMESTAMP   DEFAULT CURRENT_TIMESTAMP NOT NULL,
    -- 创建时间；审计字段
    update_time     TIMESTAMP   DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
    -- 更新时间；自动刷新
    CONSTRAINT uk_gen_table_name UNIQUE (table_name)
);

-- ========== 代码生成：字段配置 ==========
-- 业务含义：代码生成器的列级配置，一张业务表的每个参与生成的字段对应一行。
-- 使用场景：维护 Java/TS 类型映射、校验规则、表单组件类型、列表展示与查询方式，由导入过程自动推导、可人工微调。
CREATE TABLE if not exists gen_table_column
(
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    -- 主键
    table_id       BIGINT                                NOT NULL, -- 所属表配置 gen_table.id
    column_name    VARCHAR(100)                          NOT NULL, -- 列名；如 notice_type
    column_comment VARCHAR(200),                                   -- 列注释；生成字段注释与表单标签
    column_sort    INT         DEFAULT 0                 NOT NULL, -- 列序号；决定生成代码中的字段顺序
    java_field     VARCHAR(100)                          NOT NULL, -- Java/TS 驼峰字段名；如 noticeType
    java_type      VARCHAR(30)                           NOT NULL, -- Java 类型；String/Long/Integer/BigDecimal/Boolean/LocalDateTime
    ts_type        VARCHAR(20)                           NOT NULL, -- TS 类型；string/number/boolean
    is_pk          TINYINT     DEFAULT 0                 NOT NULL, -- 是否主键；1=是
    is_required    TINYINT     DEFAULT 0                 NOT NULL, -- 是否必填；1=生成 @NotNull/@NotBlank 与前端 required 规则
    is_insert      TINYINT     DEFAULT 0                 NOT NULL, -- 新增表单是否显示；1=显示
    is_edit        TINYINT     DEFAULT 0                 NOT NULL, -- 编辑表单是否显示；1=显示
    is_list        TINYINT     DEFAULT 0                 NOT NULL, -- 列表是否展示该列；1=展示
    is_query       TINYINT     DEFAULT 0                 NOT NULL, -- 是否作为查询条件；1=生成到 Query 模型与搜索表单
    query_type     VARCHAR(10) DEFAULT 'EQ'              NOT NULL, -- 查询匹配方式；EQ=精确 / LIKE=CONTAINING 模糊
    html_type      VARCHAR(20) DEFAULT 'input'           NOT NULL, -- 表单组件；input/textarea/select/radio/radio-button/switch/number
    options_json   VARCHAR(1000),                                  -- select/radio 静态选项 JSON；如 [{"value":"0","label":"通知"}]；select 配 dict 字典时优先走字典接口
    dict_type      VARCHAR(50),                                    -- select/radio 字典编码；配置后前端下拉走 /dict/item/options/{dictType}
    min_length     INT,                                            -- 字符串最小长度 / 数值最小值；生成 @Size(min)/@Min
    max_length     INT,                                            -- 字符串最大长度 / 数值上限占位；字符串生成 @Size(max)
    regex          VARCHAR(500),                                   -- 校验正则；生成 @Pattern 与前端 pattern 规则
    create_time    TIMESTAMP   DEFAULT CURRENT_TIMESTAMP NOT NULL,
    -- 创建时间；审计字段
    update_time    TIMESTAMP   DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP
    -- 更新时间；自动刷新
);
CREATE INDEX if not exists idx_gen_column_table ON gen_table_column (table_id);

-- ========== 文件管理 ==========
-- 业务含义：统一文件管理服务的元数据表，系统内所有业务场景上传文件的唯一登记入口。
-- 使用场景：文件上传落库、按文件 id 换取带签名的临时访问地址、管理端检索与删除。
-- 注意事项：业务表只保存本表主键 id（文件唯一标识），禁止存 URL 或存储路径；
--   物理文件按 根目录/yyyy/MM/uuid.ext 月份分桶落盘，路径映射规则收敛在 FileService 内部。
CREATE TABLE if not exists sys_file
(
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    -- 主键；文件唯一标识，业务模块持久化引用的唯一凭据
    original_name VARCHAR(255)                        NOT NULL, -- 原始文件名（含扩展名）；上传时的客户端文件名快照，下载回显与检索用
    storage_name  VARCHAR(100)                        NOT NULL, -- 落盘文件名；UUID + 原扩展名，与月份分桶目录共同构成存储路径（不入库完整路径）
    extension     VARCHAR(20),                                  -- 文件扩展名；小写、不含点；扩展名白名单校验依据
    content_type  VARCHAR(100),                                 -- MIME 类型；上传时快照，下载响应头回显
    size          BIGINT                              NOT NULL, -- 文件大小（字节）；大小限制校验与列表展示
    business_key  VARCHAR(50),                                  -- 业务标识；文件归属场景（如 avatar），分类检索与治理
    create_by     BIGINT,                                       -- 创建人用户 id；审计字段
    create_time   TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    -- 创建时间；审计字段；月份分桶目录由该时间推导
    update_by     BIGINT,                                       -- 最后修改人；审计字段
    update_time   TIMESTAMP DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
    -- 更新时间；自动刷新
    deleted       BIGINT    DEFAULT 0                 NOT NULL  -- 软删标记；0=未删除，删除时=本行主键 id（物理文件由服务层一并清理）
);
CREATE INDEX if not exists idx_file_business ON sys_file (business_key, deleted);
