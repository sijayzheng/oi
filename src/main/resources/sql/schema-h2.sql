-- ========== 站内信（消息中心） ==========

-- 消息主表：三类消息（NOTICE=系统通知 / LETTER=私信 / BROADCAST=公告广播）共用；
-- 系统通知与私信为点对点（receiver_id 必填），公告广播为全员广播（receiver_id 为空，
-- 不预插点对点回执，用户侧已读/归档/删除状态由 sys_message_broadcast_state 惰性记录）
CREATE TABLE if not exists sys_message
(
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    -- 主键
    msg_type       VARCHAR(20)                           NOT NULL, -- 消息类型；NOTICE=系统通知 LETTER=私信 BROADCAST=公告广播
    sender_id      BIGINT      DEFAULT 0                 NOT NULL, -- 发送人 id；0=系统
    receiver_id    BIGINT,                                         -- 接收人 id；点对点消息必填，广播为空
    title          VARCHAR(100)                          NOT NULL, -- 消息标题
    content        VARCHAR(4000)                         NOT NULL, -- 消息内容
    attachment_ids VARCHAR(500),                                   -- 附件文件 id 列表（统一文件服务），逗号分隔
    status         VARCHAR(20) DEFAULT 'SENT'            NOT NULL, -- 消息状态；SENT=已发送 WITHDRAWN=已撤回
    send_time      TIMESTAMP   DEFAULT CURRENT_TIMESTAMP NOT NULL,
    -- 发送时间；撤回时限（5 分钟）以此为基准
    create_by      BIGINT,                                         -- 创建人；审计字段
    create_time    TIMESTAMP   DEFAULT CURRENT_TIMESTAMP NOT NULL,
    -- 创建时间；审计字段
    update_time    TIMESTAMP   DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
    -- 更新时间；自动刷新
    deleted        BIGINT      DEFAULT 0                 NOT NULL  -- 软删标记
);
CREATE INDEX if not exists idx_msg_receiver ON sys_message (receiver_id, deleted, status);
CREATE INDEX if not exists idx_msg_broadcast ON sys_message (msg_type, status, deleted);
CREATE INDEX if not exists idx_msg_sender ON sys_message (sender_id, deleted);
COMMENT ON TABLE sys_message IS '站内信消息主表';
COMMENT ON COLUMN sys_message.msg_type IS '消息类型；NOTICE=系统通知 LETTER=私信 BROADCAST=公告广播';
COMMENT ON COLUMN sys_message.sender_id IS '发送人 id；0=系统';
COMMENT ON COLUMN sys_message.receiver_id IS '接收人 id；点对点消息必填，广播为空';
COMMENT ON COLUMN sys_message.title IS '消息标题';
COMMENT ON COLUMN sys_message.content IS '消息内容';
COMMENT ON COLUMN sys_message.attachment_ids IS '附件文件 id 列表（统一文件服务），逗号分隔';
COMMENT ON COLUMN sys_message.status IS '消息状态；SENT=已发送 WITHDRAWN=已撤回';
COMMENT ON COLUMN sys_message.send_time IS '发送时间；撤回时限（5 分钟）以此为基准';

-- 点对点回执表：系统通知与私信发送时按接收人生成（收件箱行），
-- 承载用户侧已读/归档/删除状态；广播消息不生成本表行
CREATE TABLE if not exists sys_message_receipt
(
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    -- 主键
    message_id  BIGINT            NOT NULL, -- 消息 id（sys_message.id）
    receiver_id BIGINT            NOT NULL, -- 接收人 id
    read_status TINYINT DEFAULT 0 NOT NULL, -- 已读状态；0=未读 1=已读
    read_time   TIMESTAMP,                  -- 首次已读时间
    archived    TINYINT DEFAULT 0 NOT NULL, -- 归档标记；1=已归档
    deleted     BIGINT  DEFAULT 0 NOT NULL  -- 软删标记；用户删除/消息撤回时置为主键 id
);
CREATE INDEX if not exists idx_receipt_inbox ON sys_message_receipt (receiver_id, deleted, archived);
CREATE INDEX if not exists idx_receipt_msg ON sys_message_receipt (message_id);
COMMENT ON TABLE sys_message_receipt IS '站内信点对点回执（收件箱行）';
COMMENT ON COLUMN sys_message_receipt.message_id IS '消息 id（sys_message.id）';
COMMENT ON COLUMN sys_message_receipt.receiver_id IS '接收人 id';
COMMENT ON COLUMN sys_message_receipt.read_status IS '已读状态；0=未读 1=已读';
COMMENT ON COLUMN sys_message_receipt.read_time IS '首次已读时间';
COMMENT ON COLUMN sys_message_receipt.archived IS '归档标记；1=已归档';

-- 广播个性化状态表：公告广播的用户侧已读/归档/删除状态，
-- 惰性创建（用户首次标记时才有行），万级广播不产生全量行膨胀
CREATE TABLE if not exists sys_message_broadcast_state
