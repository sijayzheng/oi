package cn.sijay.oi.common.exception;

import lombok.Getter;

/**
 * 业务失败码枚举，项目内所有业务异常的标准错误码来源。
 *
 * <p><b>层级化编码规则</b>：{@code 6XXXXX}，共 6 位。
 * <pre>
 *   6        —— 业务失败标识位（与 {@code Result} 错误码约定一致：业务码 >=600）
 *   XX       —— 业务模块段（2 位，每模块独占 1 个千位段，即 1000 个错误码）
 *   XXX      —— 模块内错误序号（3 位，001~999，预留 000 作为模块级通用失败）
 * </pre>
 * 完整错误码 = {@link #BASE_CODE} + 模块段 × {@link #SEGMENT_SIZE} + 错误序号。
 *
 * <p><b>模块分段分配表</b>（错误码区间 → 模块）：
 * <pre>
 *   600000~600999  通用（跨模块复用）
 *   601000~601999  用户（sys_user）
 *   602000~602999  角色（sys_role）
 *   603000~603999  菜单/权限（sys_menu）
 *   604000~604999  参数配置（sys_config）
 *   605000~605999  字典（sys_dict_type / sys_dict_item）
 *   606000~606999  文件管理（sys_file）
 *   607000~607999  站内信（sys_message / receipt / broadcast_state）
 *   608000~608999  任务调度（sys_job / sys_job_log / sys_job_dead_letter）
 *   609000~609999  代码生成（gen 元数据与渲染）
 *   610000~699999  预留扩展段（新增模块按序取段，禁止跳段占用）
 * </pre>
 *
 * <p><b>扩展方式</b>：在对应模块分段内按序号新增枚举常量，注释须说明业务场景与触发条件；
 * 新业务模块从 608 段之后开始取段。单模块错误码上限 999 个（序号 000 保留）。
 *
 * <p><b>使用示例</b>：
 * <pre>{@code
 * if (userMapper.existsByUsername(username)) {
 *     throw new BusinessException(BusinessErrorCode.USER_USERNAME_EXISTS);
 * }
 * }</pre>
 *
 * @author sijay
 */
@Getter
public enum BusinessErrorCode implements ErrorCode {

    // ==================== 通用 600000~600999 ====================

    /**
     * 请求参数错误；触发条件：业务层校验不通过，且不属于 Bean Validation 管辖的复杂参数规则。
     */
    COMMON_PARAM_ERROR(0, 1, "请求参数错误"),

    /**
     * 数据不存在；触发条件：按 ID/编码查询目标记录时结果为空，且业务要求必须存在。
     */
    COMMON_DATA_NOT_FOUND(0, 2, "数据不存在"),

    /**
     * 数据重复；触发条件：违反唯一性业务规则（如编码、键重复），且无更具体的模块级错误码可用。
     */
    COMMON_DATA_DUPLICATED(0, 3, "数据已存在"),

    // ==================== 用户 601000~601999 ====================

    /**
     * 用户名已存在；触发条件：新增/修改用户时，username 与未删除用户重复（uk_user_username 约束前置校验）。
     */
    USER_USERNAME_EXISTS(1, 1, "用户名已存在"),

    /**
     * 用户不存在；触发条件：按用户 ID 查询或操作时目标用户不存在（或已软删）。
     */
    USER_NOT_FOUND(1, 2, "用户不存在"),

    /**
     * 用户名或密码错误；触发条件：登录认证时密码比对失败。
     * 注意：不区分"用户不存在"与"密码错误"，防止账号枚举探测。
     */
    USER_CREDENTIALS_ERROR(1, 3, "用户名或密码错误"),

    /**
     * 账号已禁用；触发条件：登录或操作时 sys_user.status 为 DISABLED。
     */
    USER_DISABLED(1, 4, "账号已禁用"),

    /**
     * 原密码错误；触发条件：修改密码时旧密码比对失败（与登录 601003 的防枚举文案区分开，
     * 改密场景操作人已通过登录认证，可明确提示）。
     */
    USER_OLD_PASSWORD_ERROR(1, 5, "原密码错误"),

    /**
     * 超管账号受保护；触发条件：删除用户时目标为超级管理员（id=1），
     * 超管是系统最后可用账号，删除后会导致系统无法管理（回归测试 2026-11-03 发现）。
     */
    USER_ADMIN_PROTECTED(1, 6, "不允许删除超级管理员账号"),

    /**
     * 账号登录锁定；触发条件：同一账号连续登录失败达到 5 次，锁定 10 分钟，
     * 锁定期间拒绝一切登录请求（含密码正确请求），到期自动解锁。
     */
    USER_LOGIN_LOCKED(1, 7, "登录失败次数过多，账号已临时锁定"),

    /**
     * 密码密文无效；触发条件：SM2 加密登录的 keyId 未知/已过期，或密文损坏
     * 无法解密（前端公钥过期场景，引导重新获取公钥）。计入登录失败锁定计数。
     */
    USER_PASSWORD_DECRYPT_FAILED(1, 8, "密码密文无效或已过期，请刷新页面后重试"),

    // ==================== 角色 602000~602999 ====================

    /**
     * 角色不存在；触发条件：按角色 ID 查询或操作时目标角色不存在（或已软删）。
     */
    ROLE_NOT_FOUND(2, 1, "角色不存在"),

    /**
     * 角色编码已存在；触发条件：新增/修改角色时，code 与未删除角色重复（uk_role_code 约束前置校验）。
     */
    ROLE_CODE_EXISTS(2, 2, "角色编码已存在"),

    // ==================== 菜单/权限 603000~603999 ====================

    /**
     * 菜单不存在；触发条件：按菜单 ID 查询或操作时目标菜单不存在（或已软删）。
     */
    MENU_NOT_FOUND(3, 1, "菜单不存在"),

    /**
     * 存在子菜单，无法删除；触发条件：删除菜单时 sys_menu.parent_id 仍引用该菜单。
     */
    MENU_HAS_CHILDREN(3, 2, "存在子菜单，无法删除"),

    /**
     * 父菜单层级关系非法；触发条件：创建菜单时挂载点与节点类型不满足层级规则
     * （目录必须为根节点、菜单的父必须为目录、按钮的父必须为菜单）。
     */
    MENU_PARENT_INVALID(3, 3, "父菜单层级关系非法"),

    // ==================== 参数配置 604000~604999 ====================

    /**
     * 参数键已存在；触发条件：新增/修改配置时，config_key 与未删除配置重复（uk_config_key 约束前置校验）。
     */
    CONFIG_KEY_EXISTS(4, 1, "参数键已存在"),

    /**
     * 参数不存在；触发条件：按 config_key 或 ID 读取配置时目标记录不存在。
     */
    CONFIG_NOT_FOUND(4, 2, "参数不存在"),

    // ==================== 字典 605000~605999 ====================

    /**
     * 字典类型已存在；触发条件：新增/修改字典类型时，dict_type 与未删除记录重复（uk_dict_type_code 约束前置校验）。
     */
    DICT_TYPE_EXISTS(5, 1, "字典类型已存在"),

    /**
     * 字典不存在；触发条件：按字典编码或 ID 读取字典类型/项时目标记录不存在。
     */
    DICT_NOT_FOUND(5, 2, "字典不存在"),

    /**
     * 字典项已存在；触发条件：新增字典项时，(dict_type, item_code) 与未删除记录重复（uk_dict_item 约束前置校验）。
     */
    DICT_ITEM_EXISTS(5, 3, "字典项已存在"),

    /**
     * 字典项不存在；触发条件：按 ID 操作字典项时目标记录不存在（或已软删）。
     */
    DICT_ITEM_NOT_FOUND(5, 4, "字典项不存在"),

    // ==================== 文件管理 606000~606999 ====================

    /**
     * 上传文件为空；触发条件：未选择文件或上传内容为 0 字节。
     */
    FILE_EMPTY(6, 1, "上传文件不能为空"),

    /**
     * 文件类型不支持；触发条件：上传文件扩展名不在白名单（全局或业务自定义）内。
     */
    FILE_EXTENSION_NOT_ALLOWED(6, 2, "不支持的文件类型"),

    /**
     * 文件大小超限；触发条件：上传文件字节数超过配置的大小上限。
     */
    FILE_SIZE_EXCEEDED(6, 3, "文件大小超出限制"),

    /**
     * 文件不存在；触发条件：按 ID 查询/访问/删除文件时目标记录不存在（或已软删）。
     */
    FILE_NOT_FOUND(6, 4, "文件不存在或已删除"),

    /**
     * 文件访问签名无效；触发条件：带签名访问链接的签名校验失败或已过有效期。
     */
    FILE_SIGNATURE_INVALID(6, 5, "文件访问链接已失效"),

    /**
     * 文件上传失败；触发条件：文件落盘 IO 异常（目录不可写/磁盘异常）。
     */
    FILE_UPLOAD_FAILED(6, 6, "文件上传失败，请稍后重试"),

    // ==================== 站内信 607000~607999 ====================

    /**
     * 消息不存在；触发条件：按 id 查询/操作消息时目标不存在、已删除或已撤回。
     */
    MESSAGE_NOT_FOUND(7, 1, "消息不存在或已删除"),

    /**
     * 无权操作该消息；触发条件：访问/操作非本人收发的消息（防跨用户越权）。
     */
    MESSAGE_FORBIDDEN(7, 2, "无权操作该消息"),

    /**
     * 接收人不存在；触发条件：发送私信/系统通知时接收用户名无效或已删除。
     */
    MESSAGE_RECEIVER_NOT_FOUND(7, 3, "接收用户不存在"),

    /**
     * 接收人已禁用；触发条件：向已禁用账号发送消息。
     */
    MESSAGE_RECEIVER_DISABLED(7, 4, "接收账号已禁用，无法发送"),

    /**
     * 超过撤回时限；触发条件：消息发送超过 5 分钟后尝试撤回。
     */
    MESSAGE_WITHDRAW_EXPIRED(7, 6, "已超过可撤回时限（5 分钟）"),

    /**
     * 无权撤回；触发条件：非消息发送人尝试撤回。
     */
    MESSAGE_WITHDRAW_FORBIDDEN(7, 7, "仅发送人可撤回消息"),

    /**
     * 不能给自己发私信；触发条件：私信接收人为发送人本人。
     */
    MESSAGE_SELF_RECEIVE(7, 8, "不能给自己发送私信"),

    /**
     * 无权发布；触发条件：非管理员尝试发布系统通知/公告广播。
     */
    MESSAGE_PUBLISH_FORBIDDEN(7, 9, "仅系统管理员可发布系统通知与公告"),

    // ==================== 任务调度 608000~608999 ====================

    /**
     * 任务不存在；触发条件：按任务 id/业务键查询或操作时目标任务不存在（或已软删）。
     */
    JOB_NOT_FOUND(8, 1, "任务不存在"),

    /**
     * 任务业务键已存在；触发条件：新增任务时 job_key 与未删除任务重复（uk_job_key 约束前置校验）。
     */
    JOB_KEY_EXISTS(8, 2, "任务业务键已存在"),

    /**
     * 触发配置非法；触发条件：CRON 表达式解析失败，或 fixed-rate/fixed-delay 周期值非法（&lt;1000ms）。
     */
    JOB_TRIGGER_INVALID(8, 3, "触发配置非法"),

    /**
     * 时区配置非法；触发条件：time_zone 不是合法的时区标识（如 Asia/Shanghai）。
     */
    JOB_TIMEZONE_INVALID(8, 4, "时区配置非法"),

    /**
     * 重试配置非法；触发条件：最大重试间隔小于初始间隔，或重试参数为负值。
     */
    JOB_RETRY_CONFIG_INVALID(8, 5, "重试配置非法"),

    /**
     * 死信不存在；触发条件：按死信 id 操作时目标死信记录不存在。
     */
    JOB_DEAD_LETTER_NOT_FOUND(8, 6, "死信记录不存在"),

    /**
     * 执行记录不存在；触发条件：按执行记录 id 查询详情时目标记录不存在。
     */
    JOB_LOG_NOT_FOUND(8, 7, "执行记录不存在"),

    /**
     * 任务不可重放；触发条件：重放时目标死信对应的任务已被删除（无法定位执行逻辑）。
     */
    JOB_REPLAY_TARGET_MISSING(8, 8, "任务已删除，无法重放"),

    // ==================== 代码生成 609000~609999 ====================

    /**
     * 代码生成渲染失败；触发条件：FreeMarker 模板渲染异常（模板语法/数据模型缺失）。
     */
    GEN_RENDER_FAILED(9, 1, "代码生成渲染失败"),

    /**
     * 代码生成文件写入失败；触发条件：生成产物落盘时 IO 异常（目录不可写/磁盘异常）。
     */
    GEN_WRITE_FAILED(9, 2, "代码生成文件写入失败");

    /**
     * 业务失败码基础段（业务标识位 + 000 模块段）；
     * 所有业务错误码的起点，与 {@code Result} 类级注释中"业务码 >=600"的约定一致。
     */
    public static final int BASE_CODE = 600000;

    /**
     * 模块分段步长；每个业务模块独占一个千位段，段内最多 1000 个错误码（000 序号保留）。
     */
    public static final int SEGMENT_SIZE = 1000;

    /**
     * 业务模块段；见类级注释"模块分段分配表"。
     * 取值范围：0~99（0=通用，1~5 已分配，6~99 预留新模块）。
     */
    private final int moduleSegment;

    /**
     * 模块内错误序号；同一模块内唯一，取值范围 1~999。
     */
    private final int sequence;

    /**
     * 错误描述；面向用户的提示文案，透传至 {@code Result.message}。
     */
    private final String message;

    /**
     * 完整错误码 = BASE_CODE + 模块段 × SEGMENT_SIZE + 错误序号；
     * 透传至 {@code Result.code}，前端可据此精确定位业务失败场景。
     */
    private final int code;

    /**
     * 构建业务失败码。
     *
     * @param moduleSegment 业务模块段；须在类级注释"模块分段分配表"范围内取值
     * @param sequence      模块内错误序号；取值 1~999，同模块内不得重复
     * @param message       错误描述；面向用户，非空且不含敏感信息
     */
    BusinessErrorCode(int moduleSegment, int sequence, String message) {
        this.moduleSegment = moduleSegment;
        this.sequence = sequence;
        this.message = message;
        this.code = BASE_CODE + moduleSegment * SEGMENT_SIZE + sequence;
    }
}
